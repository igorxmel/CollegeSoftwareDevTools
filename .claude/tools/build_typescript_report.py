def build():
    doc = rb.new_document()
    rb.title_page(doc, NUMBER, TOPIC)

    rb.heading(doc, "1", "Цель работы")
    rb.para(doc, GOAL)

    rb.heading(doc, "2", "Задание")
    for i, text in enumerate(TASKS, start=1):
        rb.para(doc, f"{i}. {text}")

    rb.heading(doc, "3", "Краткие теоретические сведения")
    for text in THEORY:
        rb.para(doc, text)

    rb.heading(doc, "4", "Ход работы")
    rb.subheading(doc, "4.1", "Структура проекта")
    for text in WORK_STRUCTURE:
        rb.para(doc, text)
    rb.blank(doc)
    rb.code(doc, TREE)
    rb.blank(doc)
    rb.listing(doc, SOLUTION / "tsconfig.json")

    for number, title, texts, files in WORK_TASKS:
        rb.subheading(doc, number, title)
        for text in texts:
            rb.para(doc, text)
        rb.blank(doc)
        for name in files:
            rb.listing(doc, SOLUTION / "src" / name)

    rb.subheading(doc, "4.7", "Запуск и проверка")
    rb.para(doc, CHECK_NOTE)
    rb.blank(doc)
    rb.listing(doc, SOLUTION / "src" / "main.ts")
    rb.caption(doc, "Таблица 1 - Проверка работы")
    rb.table(doc, CHECK_HEADER, CHECK_ROWS, [5.0, 11.0])

    rb.heading(doc, "5", "Ответы на контрольные вопросы")
    rb.para(doc, ANSWERS_NOTE)
    rb.blank(doc)
    for i, (question, answer) in enumerate(QUESTIONS, start=1):
        rb.para(doc, f"{i}. {question}")
        rb.para(doc, answer)
        rb.blank(doc)

    rb.heading(doc, "6", "Вывод")
    for text in CONCLUSION:
        rb.para(doc, text)

    rb.save(doc, OUT)


def md_table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def build_readme():
    parts = [f"# ПЗ №{NUMBER}. {TITLE}", "", INTRO, ""]
    parts += ["## Содержание", "",
              "- [Описание решения](#описание-решения)",
              "- [Как запустить](#как-запустить)",
              "- [Разбор заданий](#разбор-заданий)",
              "- [Проверка](#проверка)",
              "- [Теоретическая часть](#теоретическая-часть)",
              "- [Ответы на вопросы](#ответы-на-вопросы)", ""]
    parts += ["## Описание решения", "", "```", TREE, "```", ""]
    parts += [t + "\n" for t in WORK_STRUCTURE]
    parts += ["## Как запустить", ""]
    for text, cmd in RUN_STEPS:
        parts += [text, "", "```", cmd, "```", ""]
    parts += [RUN_AFTER, ""]
    parts += ["## Разбор заданий", ""]
    for _, title, texts, _files in WORK_TASKS:
        parts += [f"### {title}", ""]
        parts += [t + "\n" for t in texts]
    parts += ["## Проверка", "", CHECK_NOTE, "", md_table(CHECK_HEADER, CHECK_ROWS), ""]
    parts += ["## Теоретическая часть", ""]
    parts += [t + "\n" for t in THEORY]
    parts += ["## Ответы на вопросы", "", ANSWERS_NOTE, ""]
    for i, (q, a) in enumerate(QUESTIONS, start=1):
        parts += [f"**{i}. {q}**", "", a, ""]
    README.write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8", newline="\n")
    print(f"saved: {README.name}")


if __name__ == "__main__":
    build()
    build_readme()
