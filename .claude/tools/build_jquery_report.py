def build():
    doc = rb.new_document()
    rb.title_page(doc, 9, TOPIC)

    rb.heading(doc, "1", "Цель работы")
    rb.para(doc, GOAL)

    rb.heading(doc, "2", "Задание")
    for i, text in enumerate(TASKS, start=1):
        rb.para(doc, f"{i}. {text}")

    rb.heading(doc, "3", "Краткие теоретические сведения")
    for text in THEORY:
        rb.para(doc, text)

    rb.heading(doc, "4", "Ход работы")
    rb.para(doc, FILES_NOTE)
    rb.blank(doc)
    for number, title, comment in WORK:
        rb.subheading(doc, number, title)
        rb.para(doc, comment)
        rb.blank(doc)

    rb.subheading(doc, "4.6", "Листинги")
    for name in ("index.html", "styles.css", "script.js"):
        rb.listing(doc, SOLUTION / name)

    rb.heading(doc, "5", "Результат работы")
    for text in CHECK:
        rb.para(doc, text)

    rb.heading(doc, "6", "Ответы на контрольные вопросы")
    for i, (question, answer) in enumerate(ANSWERS, start=1):
        rb.para(doc, f"{i} {question}")
        rb.para(doc, answer)
        rb.blank(doc)

    rb.heading(doc, "7", "Вывод")
    for text in CONCLUSION:
        rb.para(doc, text)

    rb.save(doc, OUT)


if __name__ == "__main__":
    build()
