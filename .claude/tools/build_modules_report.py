def listing(doc, path, caption_text=None):
    rb.listing(doc, path, caption_text, width=76)


def build():
    doc = rb.new_document()
    rb.title_page(doc, 15, TOPIC)

    rb.heading(doc, "1", "Цель работы")
    rb.para(doc, GOAL)

    rb.heading(doc, "2", "Задание")
    for i, text in enumerate(TASKS, start=1):
        rb.para(doc, f"{i}. {text}")
    rb.blank(doc)
    rb.para(doc, VARIANT)

    rb.heading(doc, "3", "Краткие теоретические сведения")
    for text in THEORY:
        rb.para(doc, text)

    rb.heading(doc, "4", "Ход работы")
    rb.subheading(doc, "4.1", "Первый модуль")
    rb.para(doc, FIRST_NOTE)
    rb.blank(doc)
    listing(doc, SOLUTION / "spam-check.js")

    rb.subheading(doc, "4.2", "Второй модуль")
    rb.para(doc, SECOND_NOTE)
    rb.blank(doc)
    listing(doc, SOLUTION / "message-checker.js")

    rb.subheading(doc, "4.3", "Страница для проверки")
    rb.para(doc, HTML_NOTE)
    rb.blank(doc)
    listing(doc, SOLUTION / "index.html")

    rb.subheading(doc, "4.4", "Проверка работы")
    rb.para(doc, CHECK_NOTE)
    rb.blank(doc)
    rb.caption(doc, "Таблица 1 - Результаты проверки сообщений")
    rb.table(doc, CHECK_HEADER, CHECK, [10.0, 6.0])

    rb.heading(doc, "5", "Ответы на контрольные вопросы")
    rb.para(
        doc,
        "Контрольных вопросов в методичке этого занятия нет, поэтому вопросы составлены "
        "по теоретической части.",
    )
    for i, (question, answer) in enumerate(ANSWERS, start=1):
        rb.para(doc, f"{i}. {question}")
        rb.para(doc, answer)

    rb.heading(doc, "6", "Вывод")
    for text in CONCLUSION:
        rb.para(doc, text)

    rb.save(doc, OUT)


if __name__ == "__main__":
    build()
