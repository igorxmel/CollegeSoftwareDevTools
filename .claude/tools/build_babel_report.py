def listing(doc, path, caption_text=None):
    rb.listing(doc, path, caption_text, width=76)


def build():
    doc = rb.new_document()
    rb.title_page(doc, 14, TOPIC)

    rb.heading(doc, "1", "Цель работы")
    rb.para(doc, GOAL)

    rb.heading(doc, "2", "Задание")
    for i, text in enumerate(TASKS, start=1):
        rb.para(doc, f"{i}. {text}")

    rb.heading(doc, "3", "Краткие теоретические сведения")
    for text in THEORY:
        rb.para(doc, text)

    rb.heading(doc, "4", "Ход работы")
    rb.subheading(doc, "4.1", "Установка и настройка Babel")
    rb.para(doc, WORK_SETUP)
    rb.blank(doc)
    rb.code(doc, "npm init -y\nnpm install --save-dev @babel/core @babel/cli @babel/preset-env")
    rb.blank(doc)
    rb.para(doc, "Проверка установки:")
    rb.blank(doc)
    rb.code(doc, "npx babel --version")
    rb.code(doc, VERSION_OUTPUT)
    rb.blank(doc)
    listing(doc, SOLUTION / "package.json")
    listing(doc, SOLUTION / "babel.config.json")

    rb.subheading(doc, "4.2", "Транспиляция современного JavaScript")
    rb.para(doc, SCRIPT_NOTE)
    rb.blank(doc)
    listing(doc, SOLUTION / "script.js", "Листинг исходного файла script.js:")
    rb.para(doc, SCRIPT_DEFAULT_NOTE)
    rb.blank(doc)
    listing(doc, SOLUTION / "dist" / "script.js", "Листинг файла dist/script.js:")
